// uiBruteForceUsers lists users with their brute force status.
func (h *Handler) uiBruteForceUsers(w http.ResponseWriter, r *http.Request, p *principal) error {
	realm, err := h.realmFor(r, p, permQueryUsers)
	if err != nil {
		return err
	}
	q := userQuery(r)
	if s := r.URL.Query().Get("search"); s != "" {
		q.Search = s
	}
	users, err := h.Svc.Store.SearchUsers(r.Context(), realm.ID, q)
	if err != nil {
		return err
	}
	reps := make([]UserRep, len(users))
	for i, u := range users {
		reps[i] = userToRep(u)
	}
	if err := h.visibleAttributes(r, realm, reps); err != nil {
		return err
	}
	out := make([]map[string]any, 0, len(reps))
	for i, rep := range reps {
		var m map[string]any
		b, _ := json.Marshal(rep)
		json.Unmarshal(b, &m)
		st, err := h.Svc.LockStatus(r.Context(), realm, users[i].ID)
		if err != nil {
			return err
		}
		m["bruteForceStatus"] = st
		if r.URL.Query().Get("briefRepresentation") == "true" {
			delete(m, "requiredActions")
			delete(m, "disableableCredentialTypes")
			delete(m, "notBefore")
			delete(m, "totp")
		}
		out = append(out, m)
	}
	return ok(w, out)
}

// uiSessions lists the realm's sessions (type ALL, REGULAR or OFFLINE).
func (h *Handler) uiSessions(w http.ResponseWriter, r *http.Request, p *principal) error {
	realm, err := h.realmFor(r, p, permViewUsers)
	if err != nil {
		return err
	}
	ctx := r.Context()
	typ := r.URL.Query().Get("type")
	type sessionRep struct {
		UserSessionRep
		TransientUser bool   `json:"transientUser"`
		Type          string `json:"type"`
	}
	var out []sessionRep
	add := func(sessions []*model.UserSession, kind string) error {
		reps, err := h.sessionsToRep(r, realm, sessions, map[string]*model.User{})
		if err != nil {
			return err
		}
		for _, rep := range reps {
			out = append(out, sessionRep{UserSessionRep: rep, Type: kind})
		}
		return nil
	}
	if typ == "" || typ == "ALL" || typ == "REGULAR" {
		sessions, err := h.Svc.Store.ListRealmSessions(ctx, realm.ID)
		if err != nil {
			return err
		}
		if err := add(sessions, "REGULAR"); err != nil {
			return err
		}
	}
	if typ == "" || typ == "ALL" || typ == "OFFLINE" {
		sessions, err := h.Svc.Store.ListRealmOfflineSessions(ctx, realm.ID)
		if err != nil {
			return err
		}
		if err := add(sessions, "OFFLINE"); err != nil {
			return err
		}
	}
	search := strings.ToLower(r.URL.Query().Get("search"))
	filtered := []sessionRep{}
	for _, s := range out {
		if search == "" || strings.Contains(strings.ToLower(s.Username), search) || strings.Contains(s.IPAddress, search) {
			filtered = append(filtered, s)
		}
	}
	sort.Slice(filtered, func(i, j int) bool { return filtered[i].ID < filtered[j].ID })
	return ok(w, page(r, filtered))
}

