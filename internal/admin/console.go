func (h *Handler) uiRealmNames(w http.ResponseWriter, r *http.Request, p *principal) error {
	realms, err := h.Svc.Store.ListRealms(r.Context())
	if err != nil {
		return err
	}
	search := strings.ToLower(r.URL.Query().Get("search"))
	out := []map[string]string{}
	for _, realm := range realms {
		if !p.superAdmin && realm.ID != p.realm.ID {
			continue
		}
		if search != "" && !strings.Contains(strings.ToLower(realm.Name), search) && !strings.Contains(strings.ToLower(realm.DisplayName), search) {
			continue
		}
		e := map[string]string{"name": realm.Name}
		if realm.DisplayName != "" {
			e["displayName"] = realm.DisplayName
		}
		out = append(out, e)
	}
	return ok(w, page(r, out))
}

// page applies the first / max query parameters.
func page[T any](r *http.Request, list []T) []T {
	first := min(intParam(r, "first", 0), len(list))
	last := len(list)
	if m := intParam(r, "max", -1); m >= 0 && first+m < last {
		last = first + m
	}
	return list[first:last]
}

