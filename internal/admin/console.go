// Endpoints of Keycloak's admin console beyond the admin REST API:
// /admin/serverinfo, /admin/{realm}/console/whoami and the "ui-ext"
// extensions under /admin/realms/{realm}/ui-ext.

// serverInfoCatalog is the static part of /admin/serverinfo: the provider
// catalog of Keycloak 26 reduced to what gocloak supports (generated by
// scripts/compat/serverinfo.py).
//
//go:embed serverinfo.json
var serverInfoCatalog []byte

var started = time.Now()

func formatBytes(n uint64) string {
	switch {
	case n >= 1<<30:
		return fmt.Sprintf("%d GB", n>>30)
	case n >= 1<<20:
		return fmt.Sprintf("%d MB", n>>20)
	}
	return fmt.Sprintf("%d kB", n>>10)
}

// serverInfo implements GET /admin/serverinfo.
func (h *Handler) serverInfo(w http.ResponseWriter, r *http.Request, p *principal) error {
	var info map[string]any
	if err := json.Unmarshal(serverInfoCatalog, &info); err != nil {
		return err
	}
	up := time.Since(started)
	host, _ := os.Hostname()
	wd, _ := os.Getwd()
	version := h.Version
	if version == "" {
		version = "dev"
	}
	info["systemInfo"] = map[string]any{
		"version": version, "serverTime": time.Now().UTC().Format(time.UnixDate),
		"uptime":       fmt.Sprintf("%d days, %d hours, %d minutes, %d seconds", int(up.Hours())/24, int(up.Hours())%24, int(up.Minutes())%60, int(up.Seconds())%60),
		"uptimeMillis": up.Milliseconds(), "javaVersion": runtime.Version(), "javaVendor": "The Go Authors", "javaVm": "Go runtime",
		"javaVmVersion": runtime.Version(), "javaRuntime": runtime.Version(), "javaHome": runtime.GOROOT(),
		"osName": runtime.GOOS, "osArchitecture": runtime.GOARCH, "osVersion": "", "fileEncoding": "UTF-8",
		"userName": os.Getenv("USER"), "userDir": wd, "userTimezone": time.Local.String(), "userLocale": "en_US",
		"isFipsEnabled": false, "hostname": host,
	}
	var mem runtime.MemStats
	runtime.ReadMemStats(&mem)
	free := mem.Sys - mem.HeapInuse
	info["memoryInfo"] = map[string]any{"total": mem.Sys, "totalFormated": formatBytes(mem.Sys), "used": mem.HeapInuse,
		"usedFormated": formatBytes(mem.HeapInuse), "free": free, "freeFormated": formatBytes(free),
		"freePercentage": free * 100 / max(mem.Sys, 1)}
	themes := map[string]any{}
	for _, typ := range []string{"login", "account", "email", "admin", "welcome"} {
		names := []string{"gocloak.v2"}
		if typ != "admin" && typ != "welcome" {
			names = append(names, h.ThemeNames(typ)...)
		}
		list := []map[string]any{}
		for _, n := range names {
			list = append(list, map[string]any{"name": n, "locales": []string{"en", "vi"}})
		}
		themes[typ] = list
	}
	info["themes"] = themes
	return ok(w, info)
}

// adminRoleNames are the management roles a master realm admin holds in
// every realm, as whoami lists them.
var adminRoleNames = []string{"view-realm", "view-identity-providers", "manage-identity-providers", "impersonation", "create-client",
	"manage-users", "query-realms", "view-authorization", "query-clients", "query-users", "manage-events", "manage-realm",
	"view-events", "view-users", "view-clients", "manage-authorization", "manage-clients", "query-groups"}

// whoami implements GET /admin/{realm}/console/whoami.
func (h *Handler) whoami(w http.ResponseWriter, r *http.Request, p *principal) error {
	if c, err := h.Svc.Store.GetClient(r.Context(), p.realm.ID, p.clientUUID); err != nil || c.ClientID != service.AdminConsoleClient {
		name := ""
		if c != nil {
			name = c.ClientID
		}
		return &httpError{status: http.StatusForbidden, msg: "Token issued for an application that is not the admin console: " + name, plain: true}
	}
	u := p.user
	display := strings.TrimSpace(u.FirstName + " " + u.LastName)
	if display == "" {
		display = u.Username
	}
	locale := "en"
	if v := u.Attributes["locale"]; len(v) > 0 && v[0] != "" {
		locale = v[0]
	} else if p.realm.Settings.DefaultLocale != "" {
		locale = p.realm.Settings.DefaultLocale
	}
	access := map[string][]string{}
	current := r.URL.Query().Get("currentRealm")
	if current == "" {
		current = p.realm.Name
	}
	if target, err := h.Svc.Store.GetRealmByName(r.Context(), current); err == nil {
		var roles []string
		switch {
		case p.superAdmin:
			roles = adminRoleNames
		case target.ID == p.realm.ID:
			for name := range p.mgmtRoles {
				roles = append(roles, name)
			}
			sort.Strings(roles)
		}
		if roles != nil {
			access[current] = roles
		}
	}
	attrs := u.Attributes["is_temporary_admin"]
	return ok(w, map[string]any{"userId": u.ID, "realm": p.realm.Name, "displayName": display, "locale": locale,
		"temporary": len(attrs) > 0 && attrs[0] == "true", "createRealm": p.superAdmin || p.createRealm, "realm_access": access})
}

