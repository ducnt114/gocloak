// StripTrailingSlash serves admin API paths ending with a slash as without
// it, as Keycloak (JAX-RS) does: the admin console requests /clients/.
func StripTrailingSlash(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(r.URL.Path, "/admin/realms/") && strings.HasSuffix(r.URL.Path, "/") {
			r.URL.Path = strings.TrimSuffix(r.URL.Path, "/")
			r.URL.RawPath = ""
		}
		next.ServeHTTP(w, r)
	})
}

// bufferWriter captures a response written by a handler.
type bufferWriter struct {
	header http.Header
	status int
	body   bytes.Buffer
}

func (b *bufferWriter) Header() http.Header         { return b.header }
func (b *bufferWriter) Write(p []byte) (int, error) { return b.body.Write(p) }
func (b *bufferWriter) WriteHeader(code int)        { b.status = code }

// uiUpdateRealm implements PUT /ui-ext: the console saves the realm and,
// in "upConfig", its user profile in one request.
func (h *Handler) uiUpdateRealm(w http.ResponseWriter, r *http.Request, p *principal) error {
	body, err := io.ReadAll(http.MaxBytesReader(nil, r.Body, 10<<20))
	if err != nil {
		return badRequest("Invalid body")
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(body, &fields); err != nil {
		return badRequest("Invalid JSON: " + err.Error())
	}
	up, hasUP := fields["upConfig"]
	delete(fields, "upConfig")
	if hasUP && string(up) != "null" {
		rec := &bufferWriter{header: http.Header{}, status: http.StatusOK}
		r2 := r.Clone(r.Context())
		r2.Body = io.NopCloser(bytes.NewReader(up))
		if err := h.putUserProfile(rec, r2, p); err != nil {
			return err
		}
		if rec.status >= 300 {
			for k, v := range rec.header {
				w.Header()[k] = v
			}
			w.WriteHeader(rec.status)
			w.Write(rec.body.Bytes())
			return nil
		}
	}
	rest, _ := json.Marshal(fields)
	r3 := r.Clone(r.Context())
	r3.Body = io.NopCloser(bytes.NewReader(rest))
	return h.updateRealm(w, r3, p)
}
