// uiFlows lists flows with what uses them.
func (h *Handler) uiFlows(w http.ResponseWriter, r *http.Request, p *principal) error {
	realm, err := h.realmFor(r, p, permViewRealm)
	if err != nil {
		return err
	}
	ctx := r.Context()
	flows, err := h.Svc.Store.ListFlows(ctx, realm.ID)
	if err != nil {
		return err
	}
	s := realm.Settings
	defaults := map[string]bool{}
	for _, a := range []string{s.BrowserFlow, s.RegistrationFlow, s.DirectGrantFlow, s.ResetCredentialsFlow,
		s.ClientAuthenticationFlow, s.FirstBrokerLoginFlow, s.DockerAuthenticationFlow} {
		defaults[a] = true
	}
	clients, err := h.Svc.Store.ListClients(ctx, realm.ID, "", 0, 0)
	if err != nil {
		return err
	}
	idps, err := h.Svc.Store.ListIdentityProviders(ctx, realm.ID)
	if err != nil {
		return err
	}
	out := []map[string]any{}
	for _, f := range flows {
		if !f.TopLevel {
			continue
		}
		e := map[string]any{"id": f.ID, "alias": f.Alias, "builtIn": f.BuiltIn, "description": f.Description}
		var byClient, byIdP []string
		for _, c := range clients {
			for _, id := range c.FlowOverrides {
				if id == f.ID {
					byClient = append(byClient, c.ClientID)
				}
			}
		}
		for _, idp := range idps {
			if idp.FirstBrokerLoginFlowAlias == f.Alias || idp.PostBrokerLoginFlowAlias == f.Alias {
				byIdP = append(byIdP, idp.Alias)
			}
		}
		switch {
		case defaults[f.Alias]:
			e["usedBy"] = map[string]any{"type": "DEFAULT", "values": []string{f.Alias}}
		case len(byClient) > 0:
			e["usedBy"] = map[string]any{"type": "SPECIFIC_CLIENTS", "values": byClient}
		case len(byIdP) > 0:
			e["usedBy"] = map[string]any{"type": "SPECIFIC_PROVIDERS", "values": byIdP}
		}
		out = append(out, e)
	}
	return ok(w, out)
}

// clientRoleRep is how the console lists client roles.
type clientRoleRep struct {
	ID          string `json:"id"`
	Role        string `json:"role"`
	Client      string `json:"client"`
	ClientID    string `json:"clientId"`
	Description string `json:"description,omitempty"`
}

// mappedRoles returns the roles mapped directly to an entity of the
// role mapping dialogs (users, groups, clients, clientScopes, roles).
func (h *Handler) mappedRoles(ctx context.Context, realm *model.Realm, typ, id string) ([]*model.Role, error) {
	st := h.Svc.Store
	switch typ {
	case "users":
		if _, err := st.GetUser(ctx, realm.ID, id); err != nil {
			return nil, err
		}
		return st.UserRoles(ctx, id)
	case "groups":
		if _, err := st.GetGroup(ctx, realm.ID, id); err != nil {
			return nil, err
		}
		return st.GroupRoles(ctx, id)
	case "clients":
		if _, err := st.GetClient(ctx, realm.ID, id); err != nil {
			return nil, err
		}
		return st.ListScopeMappings(ctx, id)
	case "clientScopes":
		if _, err := st.GetClientScope(ctx, realm.ID, id); err != nil {
			return nil, err
		}
		return st.ListScopeMappings(ctx, id)
	case "roles":
		if _, err := st.GetRole(ctx, realm.ID, id); err != nil {
			return nil, err
		}
		return st.ListComposites(ctx, id)
	}
	return nil, store.ErrNotFound
}

func (h *Handler) clientRoleReps(ctx context.Context, realm *model.Realm, roles []*model.Role, r *http.Request) ([]clientRoleRep, error) {
	clients := map[string]*model.Client{}
	search := strings.ToLower(r.URL.Query().Get("search"))
	out := []clientRoleRep{}
	for _, role := range roles {
		if role.ClientID == "" {
			continue
		}
		c := clients[role.ClientID]
		if c == nil {
			var err error
			if c, err = h.Svc.Store.GetClient(ctx, realm.ID, role.ClientID); err != nil {
				continue
			}
			clients[role.ClientID] = c
		}
		if search != "" && !strings.Contains(strings.ToLower(role.Name), search) && !strings.Contains(strings.ToLower(c.ClientID), search) {
			continue
		}
		out = append(out, clientRoleRep{ID: role.ID, Role: role.Name, Client: c.ClientID, ClientID: c.ID, Description: role.Description})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Client != out[j].Client {
			return out[i].Client < out[j].Client
		}
		return out[i].Role < out[j].Role
	})
	return page(r, out), nil
}

// uiAvailableRoles lists the client roles not yet mapped to an entity.
func (h *Handler) uiAvailableRoles(w http.ResponseWriter, r *http.Request, p *principal) error {
	realm, err := h.realmFor(r, p, permViewUsers)
	if err != nil {
		return err
	}
	ctx := r.Context()
	mapped, err := h.mappedRoles(ctx, realm, r.PathValue("type"), r.PathValue("id"))
	if err != nil {
		return notFound("Could not find " + r.PathValue("type"))
	}
	have := map[string]bool{}
	for _, role := range mapped {
		have[role.ID] = true
	}
	all, err := h.Svc.Store.ListAllRoles(ctx, realm.ID)
	if err != nil {
		return err
	}
	var available []*model.Role
	for _, role := range all {
		if role.ClientID != "" && !have[role.ID] && role.ID != r.PathValue("id") {
			available = append(available, role)
		}
	}
	reps, err := h.clientRoleReps(ctx, realm, available, r)
	if err != nil {
		return err
	}
	return ok(w, reps)
}

// uiEffectiveRoles lists the client roles an entity has through its
// mappings and composites.
func (h *Handler) uiEffectiveRoles(w http.ResponseWriter, r *http.Request, p *principal) error {
	realm, err := h.realmFor(r, p, permViewUsers)
	if err != nil {
		return err
	}
	ctx := r.Context()
	var roles []*model.Role
	if r.PathValue("type") == "users" {
		if _, err := h.Svc.Store.GetUser(ctx, realm.ID, r.PathValue("id")); err != nil {
			return notFound("Could not find user")
		}
		roles, err = h.Svc.EffectiveRoles(ctx, realm.ID, r.PathValue("id"))
	} else {
		var mapped []*model.Role
		if mapped, err = h.mappedRoles(ctx, realm, r.PathValue("type"), r.PathValue("id")); err != nil {
			return notFound("Could not find " + r.PathValue("type"))
		}
		if r.PathValue("type") == "groups" {
			g, _ := h.Svc.Store.GetGroup(ctx, realm.ID, r.PathValue("id"))
			if mapped, err = h.groupRolesWithAncestors(ctx, realm, g); err != nil {
				return err
			}
		}
		roles, err = h.Svc.ExpandComposites(ctx, realm.ID, mapped)
	}
	if err != nil {
		return err
	}
	reps, err := h.clientRoleReps(ctx, realm, roles, r)
	if err != nil {
		return err
	}
	return ok(w, reps)
}

