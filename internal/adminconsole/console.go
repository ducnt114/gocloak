func secureContext(r *http.Request, base string) bool {
	if strings.HasPrefix(base, "https://") {
		return true
	}
	u, err := url.Parse(base)
	if err != nil {
		return false
	}
	host := u.Hostname()
	if host == "localhost" || strings.HasSuffix(host, ".localhost") {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}

func (h *Handler) index(w http.ResponseWriter, r *http.Request) {
	realm, err := h.Svc.Store.GetRealmByName(r.Context(), r.PathValue("realm"))
	if err != nil || !realm.Enabled {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Cache-Control", "no-cache, no-store, must-revalidate")
	w.Header().Set("X-Frame-Options", "SAMEORIGIN")
	w.Header().Set("Content-Security-Policy", "frame-src 'self'; frame-ancestors 'self'; object-src 'none';")
	if h.Assets == nil {
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.WriteHeader(http.StatusServiceUnavailable)
		w.Write([]byte(`<!doctype html><html><head><meta charset="utf-8"><title>Admin console not installed</title></head>
<body style="font-family:system-ui,sans-serif;max-width:640px;margin:48px auto;padding:0 16px">
<h1>The admin console is not installed</h1>
<p>The admin console is not part of the gocloak binary. Download it with</p>
<pre>gocloak download-admin-console --dir admin-console</pre>
<p>and start gocloak with <code>--admin-console-dir admin-console</code>. The admin REST API works without it.</p>
</body></html>`))
		return
	}
	base := h.URLs.Base(r)
	resourceURL := "/resources/" + h.ResourceVersion + "/admin/gocloak.v2"
	commonURL := "/resources/" + h.ResourceVersion + "/common/gocloak"
	imports, _ := json.Marshal(map[string]any{"imports": map[string]string{
		"react":             commonURL + "/vendor/react/react.production.min.js",
		"react/jsx-runtime": commonURL + "/vendor/react/react-jsx-runtime.production.min.js",
		"react-dom":         commonURL + "/vendor/react-dom/react-dom.production.min.js",
	}})
	env, _ := json.Marshal(map[string]string{
		"serverBaseUrl": base, "adminBaseUrl": base, "authUrl": base, "authServerUrl": base,
		"realm": realm.Name, "clientId": service.AdminConsoleClient, "resourceUrl": resourceURL,
		"logo": "", "logoUrl": "", "consoleBaseUrl": "/admin/" + realm.Name + "/console/",
		"masterRealm": service.MasterRealm, "resourceVersion": h.ResourceVersion,
	})
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	err = indexTmpl.Execute(w, map[string]any{
		"ResourceURL": resourceURL, "CommonURL": commonURL, "ImportMap": string(imports),
		"SecureContext": secureContext(r, base), "Entry": h.Assets.Entry, "Styles": h.Assets.Styles,
		"Imports": h.Assets.Imports, "Environment": string(env),
	})
	if err != nil {
		h.Log.Error("render admin console", "err", err)
	}
}

// config is the keycloak.json of the console client.
func (h *Handler) config(w http.ResponseWriter, r *http.Request) {
	realm, err := h.Svc.Store.GetRealmByName(r.Context(), r.PathValue("realm"))
	if err != nil {
		http.NotFound(w, r)
		return
	}
	ssl := realm.Settings.SSLRequired
	if ssl == "" {
		ssl = "external"
	}
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]any{"realm": realm.Name, "auth-server-url": h.URLs.Base(r) + "/",
		"ssl-required": ssl, "resource": service.AdminConsoleClient, "public-client": true, "confidential-port": 0})
}

func (h *Handler) adminResource(w http.ResponseWriter, r *http.Request) {
	if h.Assets == nil {
		http.NotFound(w, r)
		return
	}
	name := "resources/" + r.PathValue("path")
	if logo, ok := brandFiles[name]; ok {
		serveFS(w, r, brandFS, logo)
		return
	}
	serveFS(w, r, h.Assets.admin, name)
}

func (h *Handler) commonResource(w http.ResponseWriter, r *http.Request) {
	if h.Assets == nil {
		http.NotFound(w, r)
		return
	}
	serveFS(w, r, h.Assets.common, r.PathValue("path"))
}

