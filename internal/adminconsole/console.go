// Handler serves the console's page, files and translations.
type Handler struct {
	Svc    *service.Service
	URLs   oidc.URLs
	Log    *slog.Logger
	Assets *Assets // nil when the console is not installed
	// Whoami serves /admin/{realm}/console/whoami (an admin API endpoint).
	Whoami http.Handler
	// ResourceVersion is the path segment versioning the console's files.
	ResourceVersion string
}

// Register adds the console routes to mux.
func (h *Handler) Register(mux *http.ServeMux) {
	mux.HandleFunc("GET /admin", h.redirectMaster)
	mux.HandleFunc("GET /admin/{$}", h.redirectMaster)
	// one pattern for /admin/{realm}/console/...: more specific ones would
	// conflict with /admin/realms/{realm}
	mux.HandleFunc("GET /admin/{realm}/{rest...}", h.consolePath)
	mux.HandleFunc("GET /resources/{version}/admin/gocloak.v2/{path...}", h.adminResource)
	mux.HandleFunc("GET /resources/{version}/common/gocloak/{path...}", h.commonResource)
	mux.HandleFunc("GET /resources/{realm}/admin/{locale}", h.translations)
}

func (h *Handler) consolePath(w http.ResponseWriter, r *http.Request) {
	switch r.PathValue("rest") {
	case "console":
		http.Redirect(w, r, r.URL.Path+"/", http.StatusFound)
	case "console/":
		h.index(w, r)
	case "console/config":
		h.config(w, r)
	case "console/whoami":
		if h.Whoami != nil {
			h.Whoami.ServeHTTP(w, r)
			return
		}
		http.NotFound(w, r)
	default:
		http.NotFound(w, r)
	}
}

func (h *Handler) redirectMaster(w http.ResponseWriter, r *http.Request) {
	http.Redirect(w, r, h.URLs.Base(r)+"/admin/"+service.MasterRealm+"/console/", http.StatusFound)
}

