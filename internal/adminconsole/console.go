// translations serves the console's messages as Keycloak does: a list of
// key / value pairs.
func (h *Handler) translations(w http.ResponseWriter, r *http.Request) {
	if h.Assets == nil {
		http.NotFound(w, r)
		return
	}
	if _, err := h.Svc.Store.GetRealmByName(r.Context(), r.PathValue("realm")); err != nil {
		http.NotFound(w, r)
		return
	}
	msgs := h.Assets.Messages(r.PathValue("locale"))
	for code, name := range localeNames {
		msgs["locale_"+code] = name
	}
	type kv struct {
		Key   string `json:"key"`
		Value string `json:"value"`
	}
	out := make([]kv, 0, len(msgs))
	for k, v := range msgs {
		out = append(out, kv{k, v})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Key < out[j].Key })
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(out)
}
